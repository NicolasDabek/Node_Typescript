import { DataTypes, ModelStatic, Model } from 'sequelize';
import { SchemaObject } from './schemaObject.interface';

/** Type OpenAPI d'un attribut Sequelize. */
function attributeSchema(attribute: any): SchemaObject {
  const type: any = attribute.type;
  const key: string = type?.key || type?.constructor?.key || '';
  const schema: SchemaObject = {};
  if (type instanceof DataTypes.INTEGER || type instanceof DataTypes.BIGINT || type instanceof DataTypes.SMALLINT || type instanceof DataTypes.TINYINT || type instanceof DataTypes.MEDIUMINT) {
    schema.type = 'integer';
  } else if (type instanceof DataTypes.DECIMAL || type instanceof DataTypes.FLOAT || type instanceof DataTypes.DOUBLE || type instanceof DataTypes.REAL) {
    schema.type = 'number';
  } else if (type instanceof DataTypes.BOOLEAN) {
    schema.type = 'boolean';
  } else if (type instanceof DataTypes.DATEONLY) {
    schema.type = 'string'; schema.format = 'date';
  } else if (type instanceof DataTypes.DATE) {
    schema.type = 'string'; schema.format = 'date-time';
  } else if (type instanceof DataTypes.ENUM) {
    schema.type = 'string'; schema.enum = (type as any).values;
  } else if (type instanceof DataTypes.JSON) {
    schema.type = 'object';
  } else if (type instanceof DataTypes.UUID) {
    schema.type = 'string'; schema.format = 'uuid';
  } else {
    schema.type = 'string';
    if (type?.options?.length) schema.maxLength = type.options.length;
    if (key === 'TEXT') delete schema.maxLength;
  }
  if (attribute.validate?.isEmail) schema.format = 'email';
  if (isNullable(attribute)) schema.nullable = true;
  if (attribute.comment) schema.description = attribute.comment;
  return schema;
}

/** Sequelize considère un attribut nullable tant que allowNull n'est pas explicitement false (sauf clé primaire). */
const isNullable = (attribute: any) => attribute.allowNull !== false && !attribute.primaryKey;

const isGenerated = (attribute: any) => !!attribute.autoIncrement || attribute.defaultValue instanceof DataTypes.NOW || attribute._autoGenerated;

export interface ModelSchemas {
  read: SchemaObject;
  create: SchemaObject;
  update: SchemaObject;
}

/**
 * Schémas OpenAPI dérivés du modèle Sequelize (source de vérité des DTOs générés) :
 * - read : ce que renvoie l'API (champs cachés exclus),
 * - create : corps de POST (clé auto-incrémentée exclue, requis = non-null sans défaut),
 * - update : corps de PUT (tout optionnel).
 */
export function modelToSchemas(model: ModelStatic<Model>, hiddenFields: string[] = []): ModelSchemas {
  const attributes = model.getAttributes() as Record<string, any>;
  const read: SchemaObject = { type: 'object', properties: {}, required: [] };
  const create: SchemaObject = { type: 'object', properties: {}, required: [] };
  const update: SchemaObject = { type: 'object', properties: {} };

  for (const [name, attribute] of Object.entries(attributes)) {
    const schema = attributeSchema(attribute);
    const hidden = hiddenFields.includes(name);
    if (!hidden) {
      read.properties![name] = { ...schema, ...(attribute.primaryKey ? { readOnly: true } : {}) };
      if (!isNullable(attribute)) read.required!.push(name);
    }
    if (isGenerated(attribute)) continue;
    const writable = hidden ? { ...schema, writeOnly: true } : schema;
    create.properties![name] = writable;
    update.properties![name] = writable;
    if (!isNullable(attribute) && attribute.defaultValue === undefined) create.required!.push(name);
  }
  if (!read.required!.length) delete read.required;
  if (!create.required!.length) delete create.required;
  return { read, create, update };
}
